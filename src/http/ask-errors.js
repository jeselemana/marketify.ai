  'ASK_ERROR', 'ASK_TIMEOUT', 'ASK_PROVIDER_TIMEOUT', 'ASK_OUTPUT_LIMIT', 'ASK_SLOW_CONSUMER', 'ASK_EMPTY_RESPONSE',
